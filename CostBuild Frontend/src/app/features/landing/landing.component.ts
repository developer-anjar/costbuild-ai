import { Component, computed, signal, inject } from '@angular/core';
import { CommonModule } from '@angular/common';
import { Router, RouterLink } from '@angular/router';
import { AppIconComponent } from '../../shared/components/app-icon/app-icon.component';
import { RateCardService } from '../../core/services/rate-card.service';
import { EstimateService } from '../../core/services/estimate.service';
import { EstimationEngineService } from '../../core/services/estimation-engine.service';
import { RegionKey, ProjectCategory, FeatureComplexity, ProjectFeature } from '../../core/models/estimate.model';

@Component({
  selector: 'app-landing',
  standalone: true,
  imports: [CommonModule, RouterLink, AppIconComponent],
  templateUrl: './landing.component.html',
  styleUrl: './landing.component.scss'
})
export class LandingComponent {
  private readonly router = inject(Router);
  readonly rateCard = inject(RateCardService);
  private readonly estimateService = inject(EstimateService);
  private readonly estimationEngine = inject(EstimationEngineService);

  // Interactive Sample Estimator State
  readonly sampleCategory = signal<ProjectCategory>('Mobile Application');
  readonly sampleComplexity = signal<FeatureComplexity>('medium');
  readonly sampleFeatureCount = signal<number>(8);
  readonly sampleRegion = signal<RegionKey>('india');
  readonly sampleScope = signal<'mvp' | 'full'>('full');

  // Real-time calculation for sample estimator
  readonly sampleEstimate = computed(() => {
    const cat = this.sampleCategory();
    const comp = this.sampleComplexity();
    const count = this.sampleFeatureCount();
    const reg = this.sampleRegion();
    const scope = this.sampleScope();
    const features: ProjectFeature[] = Array.from({ length: count }, (_, index) => ({
      id: `sample_feature_${index}`,
      name: `Feature ${index + 1}`,
      description: 'Illustrative feature for the interactive estimator.',
      complexity: comp,
      priority: scope === 'mvp' ? 'must_have' : 'should_have',
      scope,
      estimatedHours: 0,
      estimatedCost: 0
    }));
    const estimate = this.estimationEngine.generateEstimate({
      projectName: 'Interactive Sample Estimate',
      description: 'Interactive estimate generated from the landing-page calculator.',
      category: cat,
      features,
      techStack: {
        platform: cat === 'Mobile Application' ? 'mobile' : 'web',
        frontend: 'Selected by project team',
        backend: 'Selected by project team',
        database: 'Managed database',
        authentication: 'Project dependent',
        integrations: [],
        aiRequirements: 'none',
        hosting: 'Managed cloud'
      },
      parameters: {
        region: reg,
        hiringModel: 'small_agency',
        deliveryTimeline: 'standard',
        qualityExpectation: 'standard',
        designComplexity: 'standard',
        userScale: 'early_stage',
        maintenanceIncluded: false,
        testingLevel: 'standard',
        deploymentType: 'standard_cloud'
      },
      currency: 'INR'
    });
    const scenario = estimate.scenarios.find(item =>
      item.id === (scope === 'mvp' ? 'mvp' : 'recommended')
    )!;

    return {
      totalHours: scenario.totalHours,
      totalBudget: Math.round((scenario.budgetMin + scenario.budgetMax) / 2),
      weeks: scenario.timelineWeeks,
      teamSize: estimate.team.length,
      minBudget: scenario.budgetMin,
      maxBudget: scenario.budgetMax
    };
  });

  // FAQ Items
  readonly faqs = signal([
    {
      q: 'How does CostBuild AI compute software cost estimates?',
      a: 'CostBuild AI uses a deterministic rate-card calculation engine calibrated against actual engineering sprints, regional developer rate indexes (India, US, Europe), architectural complexity weights, QA ratios, and deployment buffers. Every calculation is fully auditable and reconcilable.',
      open: true
    },
    {
      q: 'Are the estimates guaranteed fixed-bid contract quotes?',
      a: 'No. Estimates generated by CostBuild AI are illustrative decision-support projections to help founders and engineering teams budget, scope MVP phases, and negotiate with agencies. A formal engineering statement of work (SOW) is recommended before signing binding contracts.',
      open: false
    },
    {
      q: 'Can I estimate an MVP versus a full-featured commercial product?',
      a: 'Yes! Compare Lean MVP (essential launch features), Startup Standard (a practical first release), and Growth Ready (the complete planned scope).',
      open: false
    },
    {
      q: 'What types of software projects can I estimate?',
      a: 'CostBuild AI supports SaaS platforms, B2B/B2C Marketplaces, On-demand Mobile Apps (iOS/Android), AI/LLM applications, E-commerce storefronts, Internal Business Management Tools, and Freelance Portfolios.',
      open: false
    },
    {
      q: 'Can I export or print the estimation report for stakeholders?',
      a: 'Yes. Every estimate report includes high-resolution browser printing with dedicated CSS `@media print` formatting, PDF generation, and JSON specification export for your team or investors.',
      open: false
    },
    {
      q: 'Can I track projects after completing an estimate?',
      a: 'Yes. You can convert any saved estimate into a tracked execution project with status tracking (Planning, In Progress, Completed), feature checklist completions, and engineering notes.',
      open: false
    }
  ]);

  toggleFaq(index: number): void {
    this.faqs.update(list =>
      list.map((item, i) => (i === index ? { ...item, open: !item.open } : item))
    );
  }

  // Transfer sample calculator inputs into full wizard
  transferToFullWizard(): void {
    const draft = {
      step: 1,
      overview: {
        projectName: `${this.sampleCategory()} Initiative`,
        category: this.sampleCategory(),
        description: `Project configured from interactive landing page estimator with ${this.sampleFeatureCount()} target features.`,
        targetAudience: 'Early adopters and businesses',
        industry: 'Software & Technology',
        objective: 'Build market-ready initial version within planned budget.'
      },
      featuresCount: this.sampleFeatureCount(),
      complexity: this.sampleComplexity(),
      region: this.sampleRegion(),
      scope: this.sampleScope()
    };

    this.estimateService.saveDraft(draft);
    this.router.navigate(['/app/new-estimate']);
  }
}
